/*
 * BRIDGE SPOT — reports page.
 *
 * Lists the demo report catalogue plus any report generated in this browser
 * (mission builder or the "Generate report" dialog). Reports created here are
 * stored under localStorage["bridge-spot:reports"] so they survive a reload
 * and show up wherever reports are listed.
 *
 * Download produces a real file client-side — no backend required.
 *
 * FUTURE: GET /api/reports for the catalogue, POST /api/reports to generate,
 * and GET /api/reports/{id}/download for the PDF.
 */
(function initReports() {
    var ui = window.BridgeUI;
    var platform = window.BRIDGE_PLATFORM;
    if (!ui || !platform) return;

    var el = ui.el;
    var html = ui.html;
    var filter = "all";
    var search = "";

    var TYPES = [
        { value: "Inspection", module: "inspection-copilot", icon: "scan" },
        { value: "Maintenance", module: "predictive-maintenance", icon: "chartUp" },
        { value: "Safety", module: "safety-response", icon: "shield" },
        { value: "Readiness", module: "readiness-evaluator", icon: "target" }
    ];

    function customReports() {
        return ui.store.get("reports", []);
    }

    function allReports() {
        return customReports().concat(platform.REPORTS);
    }

    function typeMeta(type) {
        for (var i = 0; i < TYPES.length; i += 1) {
            if (TYPES[i].value === type) return TYPES[i];
        }
        return TYPES[0];
    }

    /* ---------------- Stats ---------------- */
    function renderStats() {
        var host = document.querySelector("[data-role='stats']");
        if (!host) return;
        var reports = allReports();
        var findings = reports.reduce(function (sum, report) {
            return sum + (report.findings || 0);
        }, 0);
        var ready = reports.filter(function (report) {
            return report.status === "ready";
        }).length;

        var stats = [
            { label: "Reports available", value: String(reports.length), delta: "Across all modules", icon: "report", tone: "flat" },
            { label: "Ready to share", value: String(ready), delta: "Signed off", icon: "check", tone: "up" },
            { label: "Findings covered", value: String(findings), delta: "Across every report", icon: "alert", tone: "down" },
            { label: "Generated locally", value: String(customReports().length), delta: "This browser", icon: "download", tone: "flat" }
        ];

        host.innerHTML = "";
        stats.forEach(function (stat) {
            var card = el("div", "kpi");
            var head = el("div", "kpi__head");
            head.appendChild(el("span", "kpi__label", stat.label));
            head.appendChild(html("span", "kpi__icon", ui.icon(stat.icon)));
            card.appendChild(head);
            card.appendChild(el("span", "kpi__value", stat.value));
            card.appendChild(el("span", "kpi__delta" + (stat.tone === "down" ? " is-down" : stat.tone === "flat" ? " is-flat" : ""), stat.delta));
            host.appendChild(card);
        });
    }

    /* ---------------- Report body ---------------- */
    function reportText(report) {
        var lines = [];
        lines.push("BRIDGE SPOT — " + report.title);
        lines.push("=".repeat(60));
        lines.push("Report ID : " + report.id);
        lines.push("Type      : " + report.type);
        lines.push("Author    : " + report.author);
        lines.push("Created   : " + report.created);
        lines.push("Findings  : " + report.findings);
        lines.push("");
        lines.push("SUMMARY");
        lines.push("-".repeat(60));
        lines.push(
            report.summary ||
                "Spot completed the " +
                    report.type.toLowerCase() +
                    " route and the vision model scored every capture. " +
                    report.findings +
                    " item(s) require attention; all other checkpoints passed."
        );
        if (report.steps && report.steps.length) {
            lines.push("");
            lines.push("MISSION STEPS");
            lines.push("-".repeat(60));
            report.steps.forEach(function (step, index) {
                lines.push(index + 1 + ". " + step);
            });
        }
        lines.push("");
        lines.push("FINDINGS");
        lines.push("-".repeat(60));
        platform.FINDINGS.slice(0, Math.max(1, report.findings)).forEach(function (finding) {
            lines.push("[" + finding.severity.toUpperCase() + "] " + finding.title + " (" + finding.asset + ", " + finding.time + ")");
        });
        lines.push("");
        lines.push("Generated by the Bridge Spot demonstration platform. Not for real-world deployment.");
        return lines.join("\n");
    }

    function openReport(report) {
        var meta = typeMeta(report.type);
        var body = document.createDocumentFragment();
        body.appendChild(
            ui.statusGrid([
                { label: "Report ID", value: report.id, tone: "info" },
                { label: "Type", value: report.type, tone: "info" },
                { label: "Findings", value: String(report.findings), tone: report.findings ? "warn" : "ok" },
                { label: "Status", value: report.status, tone: report.status === "ready" ? "ok" : "info" },
                { label: "Author", value: report.author, tone: "info" },
                { label: "Created", value: report.created, tone: "info" }
            ])
        );

        var preview = el("section", "uc-section");
        preview.appendChild(el("h4", "uc-section__title", "Preview"));
        var box = el("div", "log-box");
        box.style.maxHeight = "16rem";
        reportText(report)
            .split("\n")
            .forEach(function (line) {
                box.appendChild(el("p", null, line || " "));
            });
        preview.appendChild(box);
        body.appendChild(preview);

        ui.openModal({
            title: report.title,
            tagline: report.type + " report · " + report.created,
            icon: meta.icon,
            badge: "Demo",
            body: body,
            footer: [
                {
                    label: "Download",
                    variant: "accent",
                    dismiss: false,
                    onClick: function () {
                        ui.download(report.id + ".txt", reportText(report), "text/plain");
                        ui.toast("Downloaded " + report.id + ".txt", "ok");
                    }
                },
                { label: "Open module", dismiss: false, onClick: function () {
                    if (window.BridgeDemo) window.BridgeDemo.open(report.module);
                } },
                { label: "Close", dismiss: true }
            ]
        });
    }

    /* ---------------- Table ---------------- */
    function visibleReports() {
        var needle = search.trim().toLowerCase();
        return allReports().filter(function (report) {
            if (filter !== "all" && report.type !== filter) return false;
            if (!needle) return true;
            return (
                report.title.toLowerCase().indexOf(needle) !== -1 ||
                report.id.toLowerCase().indexOf(needle) !== -1 ||
                report.author.toLowerCase().indexOf(needle) !== -1
            );
        });
    }

    function renderTable() {
        var body = document.querySelector("[data-role='reports']");
        if (!body) return;
        body.innerHTML = "";

        var rows = visibleReports();
        if (!rows.length) {
            var empty = el("tr");
            var cell = el("td", "cell-muted", "No reports match this filter.");
            cell.colSpan = 7;
            empty.appendChild(cell);
            body.appendChild(empty);
            return;
        }

        rows.forEach(function (report) {
            var row = el("tr", "is-clickable");
            row.appendChild(
                html(
                    "td",
                    null,
                    '<span class="cell-strong">' + report.title + '</span><br><span class="cell-muted">' +
                        report.id + (report.custom ? " · generated here" : "") + "</span>"
                )
            );
            row.appendChild(el("td", null, report.type));
            row.appendChild(el("td", null, String(report.findings)));
            row.appendChild(el("td", null, report.author));
            row.appendChild(html("td", null, '<span class="cell-muted">' + report.created + "</span>"));
            row.appendChild(
                html("td", null, '<span class="chip chip--' + (report.status === "ready" ? "ok" : "info") + '">' + report.status + "</span>")
            );

            var actions = el("td");
            var wrap = el("div", "page-head__actions");
            var view = el("button", "btn btn--sm", "View");
            view.type = "button";
            view.addEventListener("click", function (event) {
                event.stopPropagation();
                openReport(report);
            });
            wrap.appendChild(view);

            var dl = el("button", "btn btn--sm btn--ghost", "Download");
            dl.type = "button";
            dl.addEventListener("click", function (event) {
                event.stopPropagation();
                ui.download(report.id + ".txt", reportText(report), "text/plain");
                ui.toast("Downloaded " + report.id + ".txt", "ok");
            });
            wrap.appendChild(dl);
            actions.appendChild(wrap);
            row.appendChild(actions);

            row.addEventListener("click", function () {
                openReport(report);
            });
            body.appendChild(row);
        });
    }

    /* ---------------- Generate ---------------- */
    function openGenerator() {
        var form = el("div", "stack");
        form.style.gap = "0.9rem";

        var typeField = el("div", "field");
        typeField.appendChild(el("label", "field__label", "Report type"));
        var select = el("select", "select");
        TYPES.forEach(function (type) {
            var option = el("option", null, type.value);
            option.value = type.value;
            select.appendChild(option);
        });
        typeField.appendChild(select);
        form.appendChild(typeField);

        var titleField = el("div", "field");
        titleField.appendChild(el("label", "field__label", "Title"));
        var input = el("input", "input");
        input.type = "text";
        input.value = "Inspection summary — " + ui.formatDateTime(new Date());
        titleField.appendChild(input);
        form.appendChild(titleField);

        var notesField = el("div", "field");
        notesField.appendChild(el("label", "field__label", "Summary notes (optional)"));
        var notes = el("textarea", "textarea");
        notes.placeholder = "Anything the reader should know before the findings…";
        notesField.appendChild(notes);
        form.appendChild(notesField);

        ui.openModal({
            title: "Generate report",
            tagline: "Builds a report from the latest mission data (demo).",
            icon: "report",
            badge: "Demo",
            body: form,
            footer: [
                {
                    label: "Generate",
                    variant: "accent",
                    onClick: function () {
                        var stored = customReports();
                        var type = select.value;
                        var report = {
                            id: "RPT-" + (2100 + stored.length),
                            title: input.value.trim() || type + " report",
                            type: type,
                            module: typeMeta(type).module,
                            created: ui.formatDateTime(new Date()),
                            author: "Spot Admin",
                            findings: Math.max(1, platform.FINDINGS.length - 2),
                            status: "ready",
                            custom: true,
                            summary: notes.value.trim() || null
                        };
                        stored.unshift(report);
                        ui.store.set("reports", stored);
                        renderStats();
                        renderTable();
                        ui.toast("Report " + report.id + " generated.", "ok");
                    }
                },
                { label: "Cancel", dismiss: true }
            ]
        });
    }

    function bindToolbar() {
        var seg = document.querySelector("[data-role='filter']");
        if (seg) {
            seg.addEventListener("click", function (event) {
                var btn = event.target.closest("[data-type]");
                if (!btn) return;
                Array.prototype.forEach.call(seg.querySelectorAll("button"), function (node) {
                    node.classList.toggle("is-active", node === btn);
                });
                filter = btn.getAttribute("data-type");
                renderTable();
            });
        }

        var searchInput = document.querySelector("[data-role='search']");
        if (searchInput) {
            searchInput.addEventListener("input", function () {
                search = searchInput.value;
                renderTable();
            });
        }

        var generate = document.querySelector("[data-role='generate']");
        if (generate) generate.addEventListener("click", openGenerator);

        var exportAll = document.querySelector("[data-role='export-all']");
        if (exportAll) {
            exportAll.addEventListener("click", function () {
                var header = "id,title,type,findings,author,created,status";
                var lines = allReports().map(function (report) {
                    return [report.id, '"' + report.title + '"', report.type, report.findings, '"' + report.author + '"', '"' + report.created + '"', report.status].join(",");
                });
                ui.download("bridge-spot-reports.csv", header + "\n" + lines.join("\n"), "text/csv");
                ui.toast("Report index exported.", "ok");
            });
        }
    }

    function start() {
        renderStats();
        renderTable();
        bindToolbar();
        ui.hydrateIcons(document);

        // Quick action on the home screen links here with ?generate=1.
        if (/[?&]generate=1/.test(window.location.search)) openGenerator();
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", start);
    } else {
        start();
    }
})();
