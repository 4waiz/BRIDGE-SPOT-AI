$ErrorActionPreference = "Stop"

$repoRoot = Split-Path $PSScriptRoot -Parent
$logDir = Join-Path $env:LOCALAPPDATA "BridgeSpotAI\logs"
if (-not (Test-Path $logDir)) {
    New-Item -ItemType Directory -Path $logDir -Force | Out-Null
}
$logFile = Join-Path $logDir "autostart.log"

function Write-Log {
    param([string]$Message)
    $stamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    Add-Content -Path $logFile -Value "$stamp $Message"
}

function Test-PortOpen {
    param([int]$Port)
    try {
        $client = New-Object System.Net.Sockets.TcpClient
        $async = $client.BeginConnect("127.0.0.1", $Port, $null, $null)
        $connected = $async.AsyncWaitHandle.WaitOne(750)
        if (-not $connected) {
            $client.Close()
            return $false
        }
        $client.EndConnect($async)
        $client.Close()
        return $true
    } catch {
        return $false
    }
}

$services = @(
    @{ Name = "Spot API"; Port = 4000; Script = Join-Path $repoRoot "scripts\start_spot.ps1" },
    @{ Name = "Assistant API"; Port = 4001; Script = Join-Path $repoRoot "scripts\start_assistant.ps1" },
    @{ Name = "Frontend"; Port = 3001; Script = Join-Path $repoRoot "scripts\start_frontend.ps1" },
    @{ Name = "Guided Tour"; Port = 8004; Script = Join-Path $repoRoot "scripts\start_guided_tour.ps1" },
    @{ Name = "Spot Voice"; Port = 5000; Script = Join-Path $repoRoot "scripts\start_voice.ps1" }
)

foreach ($svc in $services) {
    $name = $svc.Name
    $port = [int]$svc.Port
    $script = $svc.Script

    if (Test-PortOpen -Port $port) {
        Write-Log "$name already responding on port $port; skipping start."
        continue
    }

    if (-not (Test-Path $script)) {
        Write-Log "Missing script for $name at $script; skipping."
        continue
    }

    Write-Log "Starting $name via $script (port $port not responding)..."
    Start-Process -FilePath "powershell.exe" -ArgumentList "-NoProfile", "-WindowStyle", "Hidden", "-ExecutionPolicy", "Bypass", "-File", $script -WorkingDirectory $repoRoot -WindowStyle Hidden | Out-Null
}

$ports = $services | ForEach-Object { [int]$_.Port }
$deadline = (Get-Date).AddMinutes(2)
while ($true) {
    $up = $ports | Where-Object { Test-PortOpen -Port $_ }
    if ($up.Count -eq $ports.Count) {
        Write-Log "All services responding: $($up -join ', ')."
        break
    }

    if ((Get-Date) -gt $deadline) {
        Write-Log "Timeout waiting for services. Up ports: $($up -join ', ')."
        break
    }

    Start-Sleep -Seconds 5
}

# The services now serve HTTPS on 4000 and 3001 (self-signed cert in
# deployment/ssl, generated by scripts/generate_lan_cert.py). We rewrite
# Edge's auto-launch command so it opens the two https:// LAN URLs
# directly, bypassing whatever's stored in "Open custom sites" -- passing
# URLs on the CLI suppresses the startup-URL restoration path in
# Chromium. Any prior --unsafely-treat-insecure-origin-as-secure flag is
# stripped: HTTPS makes it unnecessary.
#
# The DHCP-assigned LAN IP may change across reboots, so this runs every
# boot and refreshes both the cert (if it doesn't cover the current IP)
# and the Edge launch line.
function Get-LanIPv4 {
    $wifi = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object {
            $_.AddressState -eq 'Preferred' -and
            $_.IPAddress -notmatch '^(127\.|169\.254\.)' -and
            $_.InterfaceAlias -match 'Wi-Fi|Wireless|WLAN'
        } | Select-Object -First 1
    if ($wifi) { return $wifi.IPAddress }
    $wired = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object {
            $_.AddressState -eq 'Preferred' -and
            $_.IPAddress -notmatch '^(127\.|169\.254\.)'
        } | Select-Object -First 1
    if ($wired) { return $wired.IPAddress }
    return $null
}

function Set-EdgeAutoLaunchUrls {
    param([string]$LanIp)

    $runKey = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'
    if (-not (Test-Path $runKey)) { return }

    $props = Get-ItemProperty -Path $runKey -ErrorAction SilentlyContinue
    if (-not $props) { return }

    $edgeName = $props.PSObject.Properties |
        Where-Object { $_.Name -match '^MicrosoftEdgeAutoLaunch_' } |
        Select-Object -First 1 -ExpandProperty Name
    if (-not $edgeName) { return }

    $current = [string]$props.$edgeName
    if (-not $current) { return }

    # Pull the msedge.exe path back out of whatever's in there now, so we
    # do not hardcode a Program Files path that may differ per install.
    if ($current -notmatch '^\s*"([^"]+msedge\.exe)"') {
        Write-Log "Edge auto-launch value not in expected shape; leaving alone."
        return
    }
    $exe = $matches[1]

    $urls = @("https://${LanIp}:4000/", "https://${LanIp}:3001/")
    $updated = "`"$exe`" " + ($urls -join ' ')

    if ($current -eq $updated) { return }

    Set-ItemProperty -Path $runKey -Name $edgeName -Value $updated
    Write-Log "Edge auto-launch rewritten to open $($urls -join ', ')."
}

$lanIp = Get-LanIPv4
if ($lanIp) {
    # Regenerate the cert if it doesn't already cover this LAN IP. The
    # cert file itself lives outside this script; a Python helper reads
    # the current outbound IP and writes deployment/ssl/{server.crt,key}.
    $sslDir = Join-Path $repoRoot "deployment\\ssl"
    $sslCert = Join-Path $sslDir "server.crt"
    $needsCert = -not (Test-Path $sslCert)
    if (-not $needsCert) {
        try {
            $existing = Get-PfxCertificate -FilePath $sslCert -ErrorAction Stop
            $sans = ($existing.Extensions | Where-Object { $_.Oid.FriendlyName -eq 'Subject Alternative Name' } | ForEach-Object { $_.Format($false) }) -join ' '
            if ($sans -notmatch [regex]::Escape($lanIp)) { $needsCert = $true }
        } catch { $needsCert = $true }
    }
    if ($needsCert) {
        $py = Join-Path $repoRoot "smart_assistant\\backend\\venv\\Scripts\\python.exe"
        $gen = Join-Path $repoRoot "scripts\\generate_lan_cert.py"
        if ((Test-Path $py) -and (Test-Path $gen)) {
            try {
                & $py $gen | Out-Null
                Write-Log "Regenerated LAN cert for $lanIp."
            } catch { Write-Log "Cert regeneration failed: $($_.Exception.Message)" }
        }
    }
    try {
        Set-EdgeAutoLaunchUrls -LanIp $lanIp
    } catch {
        Write-Log "Failed to update Edge auto-launch URLs: $($_.Exception.Message)"
    }
} else {
    Write-Log "No usable LAN IP found; leaving Edge auto-launch alone."
}
